"""Build public reader routes and concise, paraphrased reading guides.

Only official mirror URLs and authored notes are published, never source HTML.
Article URLs/IDs, database rows and private notes are left unchanged.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def build():
    catalogs = [json.loads((ROOT / f'newsroom/catalogs/{name}.json').read_text(encoding='utf-8')) for name in ['asml', 'lg-innotek']]
    articles = {a['id']: a for c in catalogs for a in c['articles']}
    mirrors = json.loads((ROOT / 'tools/company-reader-mirrors.json').read_text(encoding='utf-8'))
    notes = json.loads((ROOT / 'tools/company-reader-notes.json').read_text(encoding='utf-8'))
    sources = {}
    for row in mirrors:
        a = next(a for a in articles.values() if a['url'] == row['url'])
        assert a['title'] == row['title'] and row['reader_url'].startswith('https://innotek.tistory.com/')
        sources[a['url']] = {'kind': 'frame', 'url': row['reader_url'], 'provider': 'LG이노텍 공식 블로그'}
    for key, sections in notes.items():
        a = articles[key]
        assert a['url'] not in sources and len(sections) == 3
        # Keep guides short, with original wording rather than source transcription.
        assert sum(len(text.split()) for _, text in sections) < 170
        sources[a['url']] = {'kind': 'reading', 'sections': sections, 'checked': '2026-10-22'}
    assert len(mirrors) == 20 and len(notes) == 18 and len(sources) == 38
    output = '// Generated by tools/build-reader-sources.py. Public routes and authored reading notes only.\n'
    output += 'export const READER_SOURCES = ' + json.dumps(sources, ensure_ascii=False, indent=2) + ';\n'
    (ROOT / 'newsroom/reader-sources.js').write_text(output, encoding='utf-8')
    print(f'{len(mirrors)} official mirrors, {len(notes)} authored guides; no article identities changed.')

if __name__ == '__main__':
    build()
